import { lstat, readFile, realpath, writeFile } from 'node:fs/promises';
import { dirname, join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';
import { execFileSync } from 'node:child_process';
import { isMainScript } from '../release/verify.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const sourcePath = 'docs/overview.md';
const manifestPath = 'storybook/readme.json';
const imageRoot = 'docs/evidence/readme/';
const external = /^(?:https?:|mailto:)/i;
// Marked uses LF tokens; canonicalize before matching and ignore only line-ending differences in checkouts.
const markdownLines = value => value.replace(/\r\n?/g, '\n');
const sourceNotice = '<!-- Generated from docs/overview.md and storybook/readme.json. Run npm run readme:generate; do not edit this file directly. -->\n\n';

export async function readReadmeManifest(projectRoot) {
  const value = JSON.parse(await readFile(join(projectRoot, manifestPath), 'utf8'));
  if (value.schemaVersion !== 1 || value.source !== sourcePath || !Array.isArray(value.screenshots) || !value.screenshots.length || value.screenshots.length > 12) throw Error('Invalid README source manifest');
  const names = new Set();
  for (const image of value.screenshots) {
    if (!/^[a-z][a-z0-9-]*\.png$/.test(image.file) || names.has(image.file)
      || !/^[a-z0-9-]+--[a-z0-9-]+$/.test(image.story) || !['desktop', 'mobile'].includes(image.viewport)
      || typeof image.alt !== 'string' || !image.alt.trim() || typeof image.caption !== 'string' || !image.caption.trim()
      || /[\r\n<>\[\]]/.test(image.alt + image.caption)) throw Error('Invalid README screenshot selection');
    names.add(image.file);
  }
  return value;
}

/** Resolve maintained links once; generated artifacts can use commit-pinned destinations. */
export function readmeLink(href, source, destination, commit = '') {
  if (external.test(href) || href.startsWith('#')) return href;
  if (/^[a-z][a-z\d+.-]*:/i.test(href) || href.startsWith('//') || href.includes('\\')) throw Error(`Unsupported README URL: ${href}`);
  const match = /^([^#?]*)(.*)$/.exec(href);
  let decoded;
  try { decoded = decodeURIComponent(match[1]); } catch { throw Error(`Invalid README URL: ${href}`); }
  const target = posix.normalize(posix.join(posix.dirname(source), decoded));
  if (!decoded || decoded.startsWith('/') || target.startsWith('../') || target.startsWith('/') || /[\x00-\x1f\x7f\\]/.test(decoded)) throw Error(`README link leaves the project: ${href}`);
  const suffix = match[2];
  if (commit && !target.startsWith(imageRoot)) {
    if (!/^[a-f0-9]{40,64}$/.test(commit)) throw Error('Invalid README source commit');
    return `https://github.com/Luis85/production-line/blob/${commit}/projects/werk/${target.split('/').map(encodeURIComponent).join('/')}${suffix}`;
  }
  return (posix.relative(posix.dirname(destination), target) || posix.basename(target)).split('/').map(encodeURIComponent).join('/') + suffix;
}

/** Work from Markdown tokens so fenced/inline code and literal examples are never rewritten. */
export function rewriteReadmeLinks(markdown, transform) {
  function children(token) {
    if (token.type === 'table') return [...token.header, ...token.rows.flat()].map(cell => ({ raw: cell.text, tokens: cell.tokens }));
    return token.items ?? token.tokens ?? [];
  }
  function rewrite(raw, nodes) {
    let cursor = 0, result = '';
    for (const token of nodes) {
      const escaped = token.raw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replaceAll('\n', '\n[ \t]*(?:>[ \t]*)?');
      const match = new RegExp(escaped).exec(raw.slice(cursor));
      if (!match) throw Error('README Markdown contains an unsupported nested link layout');
      const at = cursor + match.index, original = match[0];
      result += raw.slice(cursor, at);
      if (token.type === 'link' || token.type === 'image') {
        const destination = transform(token.href);
        if (destination === token.href) { result += original; cursor = at + original.length; continue; }
        const start = original.lastIndexOf('](');
        if (start < 0) throw Error('README links must use inline destinations');
        const rest = original.slice(start + 2), bracket = rest.startsWith('<');
        const old = bracket ? '<' + token.href + '>' : token.href;
        if (!rest.startsWith(old)) throw Error('README link destination must be a literal URL');
        result += original.slice(0, start + 2) + (bracket ? '<' + destination + '>' : destination) + rest.slice(old.length);
      } else if (['code', 'codespan', 'html'].includes(token.type)) result += original;
      else result += children(token).length ? rewrite(original, children(token)) : original;
      cursor = at + original.length;
    }
    return result + raw.slice(cursor);
  }
  const source = markdownLines(markdown);
  return rewrite(source, marked.lexer(source));
}

export async function overviewMarkdown(projectRoot, source) {
  const manifest = await readReadmeManifest(projectRoot);
  const used = new Set();
  const markdown = source.replace(/<!-- readme-image: ([a-z0-9-]+) -->/g, (_, id) => {
    const image = manifest.screenshots.find(item => item.file === id + '.png');
    if (!image || used.has(image.file)) throw Error(`Unknown or repeated README image: ${id}`);
    used.add(image.file);
    return `![${image.alt}](evidence/readme/${image.file})\n\n*${image.caption} [Screenshot provenance](evidence/readme/README.md).*`;
  });
  if (used.size !== manifest.screenshots.length || markdown.includes('<!-- readme-image:')) throw Error('README screenshot manifest and overview slots differ');
  return markdown;
}

export async function renderReadme(projectRoot = root, options = {}) {
  const source = await readFile(join(projectRoot, sourcePath), 'utf8');
  const repository = options.repository === true;
  if (repository && options.commit) throw Error('Repository landing and release README destinations cannot be combined');
  const notice = repository ? sourceNotice.replace('docs/overview.md and storybook/readme.json', 'projects/werk/docs/overview.md and projects/werk/storybook/readme.json').replace('npm run readme:generate', 'npm --prefix projects/werk run readme:generate') : sourceNotice;
  return notice + rewriteReadmeLinks(await overviewMarkdown(projectRoot, source), href => readmeLink(href, repository ? 'projects/werk/' + sourcePath : sourcePath, 'README.md', options.commit));
}
/** Only this known Forge/Git layout authorizes a second output outside the project. */
async function repositoryLanding(projectRoot) {
  const project = await realpath(projectRoot), repository = resolve(project, '../..');
  if (project !== join(repository, 'projects', 'werk')) return null;
  let config;
  try {
    config = JSON.parse(await readFile(join(repository, 'bin/config.json'), 'utf8'));
    if (config.schemaVersion !== 1 || config.paths?.projects !== 'projects' || !(await lstat(join(repository, 'bin/forge.js'))).isFile()) return null;
  } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
  // Once a Forge checkout is identified, a failed Git inspection must not silently skip drift checks.
  const git = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: project, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  return await realpath(git) === repository ? join(repository, 'README.md') : null;
}
async function readmeOutputs(projectRoot) {
  const outputs = [{ path: join(projectRoot, 'README.md'), content: await renderReadme(projectRoot) }];
  const landing = await repositoryLanding(projectRoot);
  if (landing) outputs.push({ path: landing, content: await renderReadme(projectRoot, { repository: true }) });
  return outputs;
}
export async function checkReadme(projectRoot = root) {
  const outputs = await readmeOutputs(projectRoot);
  for (const output of outputs) if (markdownLines(await readFile(output.path, 'utf8')) !== output.content) throw Error(`${output.path} differs from its maintained source. Run npm run readme:generate and review the result.`);
  return outputs[0].content;
}
export async function generateReadmes(projectRoot = root) {
  const outputs = await readmeOutputs(projectRoot);
  for (const output of outputs) if ((await lstat(dirname(output.path))).isSymbolicLink() || !(await lstat(output.path)).isFile()) throw Error('README output must be a regular project file');
  for (const output of outputs) await writeFile(output.path, output.content);
  return outputs.map(output => output.path);
}

if (isMainScript(import.meta.url)) {
  try {
    const [action] = process.argv.slice(2);
    if (process.argv.length !== 3 || !['generate', 'check'].includes(action)) throw Error('Usage: node scripts/storybook/readme-source.mjs generate|check');
    if (action === 'generate') await generateReadmes(root);
    else await checkReadme(root);
    console.log(`README ${action === 'check' ? 'matches maintained content' : 'generated from maintained content'}.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
