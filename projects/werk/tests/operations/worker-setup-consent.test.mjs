import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, readFile, writeFile, realpath, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { ownWorkspace } from '../helpers/workspace-processes.mjs';
import { waitForInstalledNativeWork } from '../helpers/native-cli-readiness.mjs';
const execute = promisify(execFile), installer = resolve('bin/apps/worker/cli.mjs');

test('installed worker retains repository consent and edited profiles, then uses an owned task worktree', { timeout: 120000 }, async t => {
  const cwd = await realpath(await mkdtemp(join(tmpdir(), 'werk-install-consent-')));
  const entry = join(cwd, 'bin/apps/worker/cli.mjs');
  let running = false;
  const cli = async (...args) => JSON.parse((await execute(process.execPath, [entry, ...args], { cwd, timeout: 40000, maxBuffer: 1048576 })).stdout);
  const git = (...args) => execute('git', ['-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.test', ...args], { cwd });
  await ownWorkspace(t, cwd, async () => { if (running) await cli('stop'); });
  await git('init', '-b', 'main'); await git('config', 'core.autocrlf', 'false');
  await writeFile(join(cwd, 'approved.txt'), 'Committed input\n');
  await git('add', 'approved.txt'); await git('commit', '-m', 'Initial fixture');
  await execute(process.execPath, [installer, 'init'], { cwd, timeout: 40000 });
  const schema = await cli('schema');
  for (const name of ['repository status', 'repository accept', 'repository decline', 'profile list', 'profile set']) assert.ok(schema.commands[name], name);
  await cli('start', '--port', '0'); running = true;
  const detected = await cli('repository', 'status');
  assert.equal(detected.discovery.path, cwd); assert.equal(detected.discovery.decision, 'pending');
  assert.equal(detected.discovery.remote, null); assert.equal(detected.items.length, 0);
  await assert.rejects(stat(join(cwd, '.werk/worktrees')), { code: 'ENOENT' });
  await assert.rejects(stat(join(cwd, '.git/FETCH_HEAD')), { code: 'ENOENT' });
  assert.equal((await cli('repository', 'decline', '--discovery-id', detected.discovery.id)).discovery.decision, 'declined');
  await cli('stop'); running = false; await cli('start', '--port', '0'); running = true;
  assert.equal((await cli('repository', 'status')).discovery.decision, 'declined');
  const ready = await waitForInstalledNativeWork(entry, cwd, t.signal);
  assert.equal(ready.discovery.decision, 'declined'); assert.equal(ready.items.length, 0);
  const accepted = await cli('repository', 'accept', '--discovery-id', detected.discovery.id);
  assert.equal(accepted.discovery.decision, 'accepted'); assert.equal(accepted.items.length, 1);
  assert.equal(accepted.items[0].watch, false);
  await cli('queue', 'pause');
  const before = await cli('profile', 'list'), profileFile = join(cwd, 'profile-update.json');
  const profiles = [{ id: 'project-review', provider: 'codex', mode: 'mock', maxParallel: 1 }];
  await writeFile(profileFile, JSON.stringify({ expectedConfigurationHash: before.configurationHash, profiles }));
  await cli('profile', 'set', '--file', profileFile);
  let saved;
  for (let n = 0; n < 100; n++) {
    saved = await cli('profile', 'list'); if (saved.state === 'ready' && saved.configurationHash !== before.configurationHash) break;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.equal(saved.state, 'ready'); assert.deepEqual(saved.profiles, profiles); assert.notEqual(saved.configurationHash, before.configurationHash);
  await cli('stop'); running = false; await cli('start', '--port', '0'); running = true;
  assert.deepEqual((await cli('profile', 'list')).profiles, profiles);
  assert.equal((await cli('repository', 'status')).items.length, 1);
  const settingsFile = join(cwd, 'provider-settings.json');
  await writeFile(settingsFile, JSON.stringify({ provider: { id: 'openai-api', apiKey: 'fixture-never-executed', model: 'fixture' } }));
  await cli('settings', 'set', '--file', settingsFile);
  const taskFile = join(cwd, 'task.json');
  await writeFile(taskFile, JSON.stringify({ title: 'Review in worktree', instruction: 'Describe approved input', provider: 'openai-api', repository: accepted.items[0].id, paths: ['approved.txt'] }));
  await waitForInstalledNativeWork(entry, cwd, t.signal);
  assert.equal((await cli('queue', 'settings')).board.paused, true);
  await cli('file-task', 'create', '--file', taskFile);
  const board = await cli('file-task', 'list'), task = board.tasks[0];
  const detail = await cli('file-task', 'get', '--id', task.id);
  assert.equal(detail.status, 'queued'); assert.equal(detail.repository, cwd);
  assert.ok(detail.worktree.startsWith(join(cwd, '.werk', 'worktrees')));
  assert.equal(await readFile(join(cwd, 'approved.txt'), 'utf8'), 'Committed input\n');
  await cli('stop'); running = false;
});
