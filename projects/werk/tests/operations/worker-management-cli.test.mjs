import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, readFile, writeFile, realpath } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { ownWorkspace } from '../helpers/workspace-processes.mjs';
const exec = promisify(execFile), installer = resolve('bin/apps/worker/cli.mjs');
test('copied worker CLI manages drafts, tasks, queues and history without a browser', { timeout: 120000 }, async t => {
  const cwd = await realpath(await mkdtemp(join(tmpdir(), 'werk-management-cli-'))), entry = join(cwd, 'bin/apps/worker/cli.mjs'); let running = false;
  const cli = async (...args) => { const result = await exec(process.execPath, [entry, ...args], { cwd, timeout: 40000 }); return JSON.parse(result.stdout); };
  await ownWorkspace(t, cwd, async () => { if (running) await cli('stop'); });
  await exec(process.execPath, [installer, 'init', '--provider', 'openai-api'], { cwd });
  const schema = await cli('schema'); for (const name of ['feature edit', 'feature submit', 'feature result', 'feature wait', 'task retry', 'file-task priority', 'queue pause', 'session restore']) assert.ok(schema.commands[name], name);
  await cli('start', '--port', '0'); running = true;
  await cli('queue', 'pause'); const settingsFile = join(cwd, 'settings.json');
  await writeFile(settingsFile, JSON.stringify({ provider: { id: 'openai-api', apiKey: 'fixture-never-executed', model: 'fixture' }, board: { queueCapacity: 8, orchestratorQueue: 2 } }));
  await cli('settings', 'set', '--file', settingsFile); assert.equal((await cli('queue', 'settings')).board.paused, true);
  const markdown = join(cwd, 'request.md'); const raw = '---\nschemaVersion: 1\ntitle: CLI lifecycle\nstatus: draft\n---\nDescribe a feature.\n'; await writeFile(markdown, raw);
  let file = await cli('feature', 'create', '--name', 'example.md', '--markdown', markdown); assert.equal(file.markdown, raw);
  assert.equal((await cli('feature', 'list', '--status', 'draft')).files.length, 1);
  await assert.rejects(cli('feature', 'edit', '--name', 'example.md', '--markdown', markdown, '--if-match', 'stale'), error => error.code === 2 && /revision/.test(error.stderr));
  file = await cli('feature', 'edit', '--name', 'example.md', '--markdown', markdown, '--if-match', file.revision);
  await cli('feature', 'validate', '--name', 'example.md'); await cli('feature', 'submit', '--name', 'example.md', '--if-match', file.revision);
  for (let i = 0; i < 30; i++) { await cli('feature', 'list'); file = await cli('feature', 'get', '--name', 'example.md'); if (file.record?.submitted) break; await new Promise(r => setTimeout(r, 100)); }
  assert.equal(file.record.status, 'queued'); const id = file.record.sessionId;
  assert.equal(file.record.gates.phase, 'ready', 'Readiness is separate from the paused execution queue.');
  assert.equal(file.record.gates.ready, 'pass');
  assert.equal(file.record.gates.done, 'not_evaluated');
  assert.equal(file.record.executionStatus, 'queued');
  assert.equal(file.record.execution, undefined, 'A paused attempt has no before/after measurement.');
  const queuedRuns = (await cli('run', 'list', '--session-id', id)).rows;
  assert.equal(queuedRuns.length, 1);
  assert.equal(queuedRuns[0].outcome, 'queued');
  assert.equal(queuedRuns[0].startedAt, null);
  assert.equal(queuedRuns[0].before, null);
  assert.equal(queuedRuns[0].after, null);
  assert.equal(queuedRuns[0].usage.source, 'unavailable');
  await cli('task', 'rename', '--id', id, '--title', 'Renamed from CLI');
  assert.equal((await cli('task', 'get', '--id', id)).session.title, 'Renamed from CLI');
  await assert.rejects(cli('task', 'wait', '--id', id, '--timeout-ms', '1'), error => error.code === 1 && /continues/.test(error.stderr));
  assert.equal((await cli('task', 'get', '--id', id)).session.status, 'queued');
  file = await cli('feature', 'cancel', '--name', 'example.md', '--if-match', file.revision);
  assert.equal((await cli('feature', 'wait', '--name', 'example.md', '--timeout-ms', '1000')).record.status, 'cancelled');
  await cli('task', 'retry', '--id', id); assert.equal((await cli('task', 'get', '--id', id)).chat.messages.length, 4);
  await cli('task', 'cancel', '--id', id); await cli('task', 'wait', '--id', id);
  await cli('task', 'archive', '--id', id); await cli('task', 'archive', '--id', id);
  assert.equal((await cli('task', 'list', '--archived', 'true')).records.length, 1);
  await cli('task', 'restore', '--id', id); assert.equal((await cli('session', 'get', '--id', id)).session.archived, false);
  assert.equal((await cli('session', 'list')).selected, 'default');
  file = await cli('feature', 'get', '--name', 'example.md'); file = await cli('feature', 'archive', '--name', 'example.md', '--if-match', file.revision);
  assert.equal((await cli('feature', 'list', '--archived', 'true')).records.length, 1);
  await cli('feature', 'delete', '--name', 'example.md', '--if-match', file.revision); await assert.rejects(readFile(join(cwd, 'features/example.md')), { code: 'ENOENT' });
  await cli('task', 'delete', '--id', id); await cli('queue', 'resume'); assert.equal((await cli('queue', 'settings')).board.paused, false);
  await cli('stop'); running = false;
});
