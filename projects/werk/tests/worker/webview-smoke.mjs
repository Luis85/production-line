async function taskCard(title) {
  const card = page.getByRole('article', { name: title, exact: true, includeHidden: true });
  await card.waitFor({ state: 'attached' });
  if (!await card.isVisible()) {
    const disclosure = card.locator('xpath=ancestor::details[1]');
    assert.equal(await disclosure.count(), 1, 'retained work has an explicit disclosure');
    await disclosure.locator(':scope > summary').click();
  }
  return card;
}
async function selectTask(title, id) {
  await workboard(); await refresh();
  await (await taskCard(title)).getByRole('button').click();
  await until(async () => ['/request', '/review'].includes(new URL(page.url()).pathname), 'request destination');
  if (new URL(page.url()).pathname === '/review') await page.getByRole('link', { name: 'Open conversation', exact: true }).click();
  await panel().waitFor();
  await page.getByRole('heading', { name: title, exact: true, level: 1 }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/request');
  assert.equal(new URL(page.url()).searchParams.get('session'), id);
  assert.equal((await api('/api/sessions')).selected, id, 'explicit request navigation selects the exact retained task');
  assert.equal(await panel().getByRole('tab').count(), 0, 'existing request has no generic new/follow-up mode switch');
}
async function setQueue(paused) {
  if ((await api('/api/settings')).board.paused === paused) return;
  await workboard();
  await page.getByRole('button', { name: paused ? 'Pause new starts' : 'Resume new starts', exact: true }).click();
  await until(async () => (await api('/api/settings')).board.paused === paused, 'queue pause state');
}
async function complete(id) {
  await until(async () => (await api('/api/sessions')).records.find(task => task.id === id)?.status === 'completed', 'completed ' + id);
  await refresh();
}
